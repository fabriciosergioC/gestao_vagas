-- ==================== FUNÇÃO: CRIAR CLIENTE ====================
CREATE OR REPLACE FUNCTION criar_cliente(
  p_cnpj VARCHAR(20),
  p_razao_social VARCHAR(200),
  p_nome_fantasia VARCHAR(200),
  p_email VARCHAR(200),
  p_telefone VARCHAR(30),
  p_endereco TEXT,
  p_usuario_admin VARCHAR(50),
  p_senha_admin VARCHAR(200)
) RETURNS BIGINT AS $$
DECLARE
  v_cliente_id BIGINT;
BEGIN
  -- Inserir cliente
  INSERT INTO clientes (cnpj, razao_social, nome_fantasia, email, telefone, endereco)
  VALUES (p_cnpj, p_razao_social, p_nome_fantasia, p_email, p_telefone, p_endereco)
  RETURNING id INTO v_cliente_id;
  
  -- Inserir configurações padrão
  INSERT INTO configuracoes (cliente_id, valor_hora_carro, valor_hora_moto, valor_hora_caminhao, total_vagas, nome_estacionamento)
  VALUES (v_cliente_id, 10.00, 5.00, 20.00, 20, COALESCE(p_nome_fantasia, p_razao_social));
  
  -- Inserir usuário admin
  INSERT INTO usuarios (cliente_id, usuario, senha, nome, email, ativo)
  VALUES (v_cliente_id, p_usuario_admin, p_senha_admin, 'Administrador', p_email, true);
  
  RETURN v_cliente_id;
END;
$$ LANGUAGE plpgsql;

-- ==================== FUNÇÃO: LISTAR CLIENTES ====================
CREATE OR REPLACE FUNCTION listar_clientes()
RETURNS TABLE (
  id BIGINT,
  cnpj VARCHAR(20),
  razao_social VARCHAR(200),
  nome_fantasia VARCHAR(200),
  email VARCHAR(200),
  telefone VARCHAR(30),
  ativo BOOLEAN,
  total_veiculos BIGINT,
  total_usuarios BIGINT
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    c.id,
    c.cnpj,
    c.razao_social,
    c.nome_fantasia,
    c.email,
    c.telefone,
    c.ativo,
    COALESCE(v.total, 0) AS total_veiculos,
    COALESCE(u.total, 0) AS total_usuarios
  FROM clientes c
  LEFT JOIN (
    SELECT cliente_id, COUNT(*) AS total
    FROM veiculos
    WHERE saida IS NULL
    GROUP BY cliente_id
  ) v ON c.id = v.cliente_id
  LEFT JOIN (
    SELECT cliente_id, COUNT(*) AS total
    FROM usuarios
    GROUP BY cliente_id
  ) u ON c.id = u.cliente_id
  ORDER BY c.razao_social;
END;
$$ LANGUAGE plpgsql;

-- ==================== VISÃO: RESUMO MULTI-CLIENTE ====================
CREATE OR REPLACE VIEW resumo_multi_cliente AS
SELECT 
  c.id AS cliente_id,
  c.nome_fantasia,
  c.razao_social,
  c.ativo,
  COUNT(DISTINCT v.id) FILTER (WHERE v.saida IS NULL) AS veiculos_no_patio,
  COUNT(DISTINCT v.vaga) FILTER (WHERE v.saida IS NULL) AS vagas_ocupadas,
  cfg.total_vagas,
  cfg.total_vagas - COUNT(DISTINCT v.vaga) FILTER (WHERE v.saida IS NULL) AS vagas_livres,
  COUNT(DISTINCT h.id) FILTER (WHERE h.saida >= DATE_TRUNC('month', NOW())) AS saidas_mes,
  COALESCE(SUM(h.valor_cobrado) FILTER (WHERE h.saida >= DATE_TRUNC('month', NOW())), 0) AS faturamento_mes
FROM clientes c
LEFT JOIN veiculos v ON c.id = v.cliente_id
LEFT JOIN configuracoes cfg ON c.id = cfg.cliente_id
LEFT JOIN historico h ON c.id = h.cliente_id
GROUP BY c.id, c.nome_fantasia, c.razao_social, c.ativo, cfg.total_vagas;

