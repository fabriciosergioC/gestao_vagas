-- ==================== TABELA: CLIENTES ====================
CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cnpj VARCHAR(20),
  razao_social VARCHAR(200) NOT NULL,
  nome_fantasia VARCHAR(200),
  email VARCHAR(200),
  telefone VARCHAR(30),
  endereco TEXT,
  ativo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_clientes_ativo ON clientes(ativo) WHERE ativo = true;

COMMENT ON TABLE clientes IS 'Clientes/Estacionamentos que usam o sistema';

-- ==================== TABELA: USUÁRIOS ====================
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE CASCADE,
  usuario VARCHAR(50) NOT NULL,
  senha VARCHAR(200) NOT NULL,
  nome VARCHAR(200),
  email VARCHAR(200),
  ativo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_usuarios_cliente ON usuarios(cliente_id);
CREATE INDEX IF NOT EXISTS idx_usuarios_usuario ON usuarios(usuario);
CREATE INDEX IF NOT EXISTS idx_usuarios_ativo ON usuarios(ativo) WHERE ativo = true;

-- ==================== TABELA: VEÍCULOS ====================
CREATE TABLE IF NOT EXISTS veiculos (
  id BIGINT PRIMARY KEY,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE CASCADE,
  placa VARCHAR(20) NOT NULL,
  marca VARCHAR(100) NOT NULL,
  modelo VARCHAR(100) NOT NULL,
  cor VARCHAR(50),
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('carro', 'moto', 'caminhao')),
  proprietario VARCHAR(200),
  telefone VARCHAR(30),
  vaga VARCHAR(10) NOT NULL,
  entrada TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  saida TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_veiculos_placa ON veiculos(placa);
CREATE INDEX IF NOT EXISTS idx_veiculos_cliente ON veiculos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_veiculos_cliente_no_patio ON veiculos(cliente_id, saida) WHERE saida IS NULL;

-- ==================== TABELA: HISTÓRICO ====================
CREATE TABLE IF NOT EXISTS historico (
  id BIGINT PRIMARY KEY,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE CASCADE,
  veiculo_id BIGINT,
  placa VARCHAR(20) NOT NULL,
  marca VARCHAR(100) NOT NULL,
  modelo VARCHAR(100) NOT NULL,
  cor VARCHAR(50),
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('carro', 'moto', 'caminhao')),
  proprietario VARCHAR(200),
  telefone VARCHAR(30),
  vaga VARCHAR(10) NOT NULL,
  entrada TIMESTAMP WITH TIME ZONE NOT NULL,
  saida TIMESTAMP WITH TIME ZONE NOT NULL,
  tempo_permanencia VARCHAR(20),
  valor_cobrado DECIMAL(10,2) NOT NULL DEFAULT 0,
  forma_pagamento VARCHAR(20) NOT NULL CHECK (forma_pagamento IN ('dinheiro', 'pix', 'cartao')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_historico_placa ON historico(placa);
CREATE INDEX IF NOT EXISTS idx_historico_cliente ON historico(cliente_id);
CREATE INDEX IF NOT EXISTS idx_historico_cliente_saida ON historico(cliente_id, saida DESC);

-- ==================== TABELA: CONFIGURAÇÕES ====================
CREATE TABLE IF NOT EXISTS configuracoes (
  id INTEGER NOT NULL,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE CASCADE,
  valor_hora_carro DECIMAL(10,2) NOT NULL DEFAULT 10.00,
  valor_hora_moto DECIMAL(10,2) NOT NULL DEFAULT 5.00,
  valor_hora_caminhao DECIMAL(10,2) NOT NULL DEFAULT 20.00,
  total_vagas INTEGER NOT NULL DEFAULT 20,
  nome_estacionamento VARCHAR(200) NOT NULL DEFAULT 'Estacionamento Central',
  valor_hora_adicional DECIMAL(10,2) DEFAULT 0,
  tolerancia_minutos INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT configuracoes_cliente_unique UNIQUE (cliente_id)
);

CREATE INDEX IF NOT EXISTS idx_configuracoes_cliente ON configuracoes(cliente_id);

-- ==================== TABELA: LOGS DE ACESSO ====================
CREATE TABLE IF NOT EXISTS logs_acesso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE CASCADE,
  usuario VARCHAR(100),
  acao VARCHAR(50),
  descricao TEXT,
  ip_address VARCHAR(50),
  user_agent TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_logs_cliente ON logs_acesso(cliente_id);
CREATE INDEX IF NOT EXISTS idx_logs_data ON logs_acesso(created_at DESC);

-- ==================== FUNÇÃO: UPDATE UPDATED_AT ====================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ==================== TRIGGERS ====================
DROP TRIGGER IF EXISTS update_clientes_updated_at ON clientes;
CREATE TRIGGER update_clientes_updated_at
  BEFORE UPDATE ON clientes
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_usuarios_updated_at ON usuarios;
CREATE TRIGGER update_usuarios_updated_at
  BEFORE UPDATE ON usuarios
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_veiculos_updated_at ON veiculos;
CREATE TRIGGER update_veiculos_updated_at
  BEFORE UPDATE ON veiculos
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_configuracoes_updated_at ON configuracoes;
CREATE TRIGGER update_configuracoes_updated_at
  BEFORE UPDATE ON configuracoes
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

