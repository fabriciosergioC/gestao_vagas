  RAISE NOTICE '📊 Tabela clientes criada';
  RAISE NOTICE '🔗 cliente_id adicionado em todas as tabelas';
  RAISE NOTICE '🔐 RLS habilitado';
  RAISE NOTICE '👤 Cliente padrão (ID 1) configurado';
  RAISE NOTICE '💡 Agora você pode cadastrar novos clientes pela tela de login';
END $$;
